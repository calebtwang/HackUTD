import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { build } from 'esbuild';
import { dirname, resolve } from 'node:path';

const config = JSON.parse(await readFile('cloud/deployment.json', 'utf8')) as { bindings: {name:string}[] };
await writeFile('cloud/worker-env.d.ts', `// Generated by scripts/build-webhook.ts from cloud/deployment.json.\nexport interface Env {\n${config.bindings.map(binding => `  ${binding.name}: string;`).join('\n')}\n}\n`);
const outfile = resolve('.local/cloud/worker.mjs');
await mkdir(dirname(outfile), {recursive:true});
await build({entryPoints:['cloud/worker.ts'],outfile,bundle:true,format:'esm',platform:'browser',target:'es2022',sourcemap:false,legalComments:'none'});
console.log(`Cloud webhook bundle ready: ${outfile}`);
